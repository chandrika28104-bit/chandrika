import React, { useState } from 'react';
import { AnalysisData } from '../types/career';
import { ScoreGauge } from './ScoreGauge';
import {
  CheckCircle2,
  AlertTriangle,
  Sparkles,
  Copy,
  Check,
  Download,
  Printer,
  ChevronRight,
  TrendingUp,
  DollarSign,
  HelpCircle,
  FileText,
  BadgeCheck,
  Send,
} from 'lucide-react';

interface ResultDisplayProps {
  analysis: AnalysisData;
  candidateName?: string;
  targetRole?: string;
  onSendToRewriter?: (keyword: string) => void;
  onAskCopilot?: (question: string) => void;
}

export const ResultDisplay: React.FC<ResultDisplayProps> = ({
  analysis,
  candidateName,
  targetRole,
  onSendToRewriter,
  onAskCopilot,
}) => {
  const [copiedHook, setCopiedHook] = useState(false);
  const [copiedKeyword, setCopiedKeyword] = useState<string | null>(null);

  const handleCopyHook = () => {
    if (!analysis.cover_letter_hook) return;
    navigator.clipboard.writeText(analysis.cover_letter_hook);
    setCopiedHook(true);
    setTimeout(() => setCopiedHook(false), 2000);
  };

  const handleCopyKeyword = (kw: string) => {
    navigator.clipboard.writeText(kw);
    setCopiedKeyword(kw);
    setTimeout(() => setCopiedKeyword(null), 1500);
  };

  const handleDownloadMarkdown = () => {
    const md = `# ATS & Resume Evaluation Report
Generated by AI Career Copilot · Powered by Google Gemini
Date: ${new Date().toLocaleDateString()}

## Overall ATS Match Score: ${analysis.ats_score} / 100

### Category Breakdown
- Keywords Match: ${analysis.category_scores?.keywords_match ?? 'N/A'}/100
- Experience Alignment: ${analysis.category_scores?.experience_alignment ?? 'N/A'}/100
- Hard Skills Match: ${analysis.category_scores?.hard_skills ?? 'N/A'}/100
- Soft Skills & Leadership: ${analysis.category_scores?.soft_skills ?? 'N/A'}/100
- Formatting & ATS Readability: ${analysis.category_scores?.formatting_clarity ?? 'N/A'}/100

### Executive Assessment
${analysis.summary}

### Key Strengths
${(analysis.strengths || []).map((s) => `- ${s}`).join('\n')}

### High Priority Missing Keywords
${(analysis.missing_keywords || []).map((k) => `- ${k}`).join('\n')}

### Actionable Improvements
${(analysis.improvements || []).map((i) => `- ${i}`).join('\n')}

### Seniority Level Alignment
- Candidate Estimate: ${analysis.seniority_estimate?.candidate_level || 'N/A'}
- Target Role Level: ${analysis.seniority_estimate?.role_level || 'N/A'}
- Fit Analysis: ${analysis.seniority_estimate?.alignment || 'N/A'}

### Market Compensation Benchmark
- Estimated Range: ${analysis.salary_estimate?.range || 'N/A'}
- Notes: ${analysis.salary_estimate?.notes || 'N/A'}

### Anticipated Interview Questions
${(analysis.interview_prep_questions || []).map((q, idx) => `${idx + 1}. ${q}`).join('\n')}

### Cover Letter Opening Hook
"${analysis.cover_letter_hook || ''}"
`;

    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `career-copilot-report-${Date.now()}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  const categories = [
    {
      name: 'Keywords Match',
      score: analysis.category_scores?.keywords_match ?? 75,
      desc: 'Exact match with job description terms',
    },
    {
      name: 'Experience Alignment',
      score: analysis.category_scores?.experience_alignment ?? 70,
      desc: 'Years, seniority, and scale of past projects',
    },
    {
      name: 'Hard Skills & Tools',
      score: analysis.category_scores?.hard_skills ?? 80,
      desc: 'Stack, languages, and technical frameworks',
    },
    {
      name: 'Soft Skills & Leadership',
      score: analysis.category_scores?.soft_skills ?? 85,
      desc: 'Cross-functional collaboration and communication',
    },
    {
      name: 'ATS Readability',
      score: analysis.category_scores?.formatting_clarity ?? 90,
      desc: 'Section parsing, clean headers, and metric bullet points',
    },
  ];

  return (
    <div id="evaluation-results" className="space-y-6 animate-in fade-in slide-in-from-bottom-4 duration-300">
      {/* Top Banner & Export Actions */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-4 bg-white rounded-2xl border border-slate-200 shadow-xs">
        <div>
          <div className="flex items-center gap-2">
            <span className="p-1 rounded bg-emerald-100 text-emerald-700">
              <BadgeCheck className="w-4 h-4" />
            </span>
            <h3 className="text-sm font-bold text-slate-900">
              Analysis Complete {candidateName ? `for ${candidateName}` : ''}
            </h3>
          </div>
          <p className="text-xs text-slate-500 mt-0.5">
            Evaluated with Gemini LLM structured JSON schema engine
          </p>
        </div>

        <div className="flex items-center gap-2 flex-wrap">
          <button
            onClick={handleDownloadMarkdown}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-lg transition-colors"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Export Markdown</span>
          </button>
          <button
            onClick={handlePrint}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-lg transition-colors"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print Report</span>
          </button>
        </div>
      </div>

      {/* Main Score & Category Breakdown Card */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 bg-white p-6 rounded-2xl border border-slate-200 shadow-xs">
        {/* Left: Overall Gauge */}
        <div className="lg:col-span-5 flex flex-col items-center justify-center p-6 border-b lg:border-b-0 lg:border-r border-slate-100">
          <h4 className="text-xs font-bold text-slate-400 uppercase tracking-wider mb-4">
            ATS Match Benchmark
          </h4>
          <ScoreGauge score={analysis.ats_score} size={170} />
          <p className="text-xs text-slate-500 text-center mt-4 max-w-xs leading-relaxed">
            {analysis.ats_score >= 80
              ? 'Your resume strongly aligns with this job description. High probability of passing recruiter filters.'
              : analysis.ats_score >= 65
              ? 'Moderate alignment. Adding missing high-frequency keywords and metrics will significantly boost visibility.'
              : 'Gaps detected in core qualifications or required technical tools. See recommended improvements below.'}
          </p>
        </div>

        {/* Right: Sub-Category Progress Bars */}
        <div className="lg:col-span-7 flex flex-col justify-center space-y-3.5 py-2">
          <h4 className="text-xs font-bold text-slate-400 uppercase tracking-wider mb-2">
            Multidimensional Competency Scoring
          </h4>
          {categories.map((cat) => (
            <div key={cat.name} className="space-y-1">
              <div className="flex items-center justify-between text-xs">
                <span className="font-semibold text-slate-700">{cat.name}</span>
                <span className="font-bold text-slate-900">{cat.score}%</span>
              </div>
              <div className="w-full h-2 bg-slate-100 rounded-full overflow-hidden">
                <div
                  className={`h-full rounded-full transition-all duration-700 ${
                    cat.score >= 80
                      ? 'bg-emerald-500'
                      : cat.score >= 65
                      ? 'bg-amber-500'
                      : 'bg-orange-500'
                  }`}
                  style={{ width: `${Math.min(100, Math.max(0, cat.score))}%` }}
                />
              </div>
              <p className="text-[11px] text-slate-400">{cat.desc}</p>
            </div>
          ))}
        </div>
      </div>

      {/* Seniority & Salary Estimates Bar */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {/* Seniority alignment */}
        <div className="bg-white p-5 rounded-2xl border border-slate-200 shadow-xs flex items-start gap-3.5">
          <div className="p-2.5 rounded-xl bg-blue-50 text-blue-600 shrink-0">
            <TrendingUp className="w-5 h-5" />
          </div>
          <div>
            <h4 className="text-xs font-bold uppercase tracking-wider text-slate-400">
              Seniority Calibration
            </h4>
            <div className="mt-1 flex items-center gap-2 flex-wrap text-sm font-semibold text-slate-900">
              <span>Candidate: {analysis.seniority_estimate?.candidate_level || 'Mid-Level'}</span>
              <span className="text-slate-300">→</span>
              <span>Target: {analysis.seniority_estimate?.role_level || 'Mid-Senior'}</span>
            </div>
            <p className="text-xs text-slate-600 mt-1">
              Verdict: {analysis.seniority_estimate?.alignment || 'Good career progression fit'}
            </p>
          </div>
        </div>

        {/* Salary estimate */}
        <div className="bg-white p-5 rounded-2xl border border-slate-200 shadow-xs flex items-start gap-3.5">
          <div className="p-2.5 rounded-xl bg-emerald-50 text-emerald-600 shrink-0">
            <DollarSign className="w-5 h-5" />
          </div>
          <div>
            <h4 className="text-xs font-bold uppercase tracking-wider text-slate-400">
              Market Compensation Range
            </h4>
            <div className="mt-1 text-sm font-extrabold text-emerald-700">
              {analysis.salary_estimate?.range || '$120,000 - $155,000 / year'}
            </div>
            <p className="text-xs text-slate-600 mt-1">
              {analysis.salary_estimate?.notes || 'Based on market benchmarks for this tech stack and experience tier.'}
            </p>
          </div>
        </div>
      </div>

      {/* Executive Summary */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs">
        <h4 className="text-xs font-bold text-slate-400 uppercase tracking-wider mb-2 flex items-center gap-2">
          <Sparkles className="w-4 h-4 text-orange-500" />
          Executive Synthesis
        </h4>
        <p className="text-sm text-slate-700 leading-relaxed font-normal">
          {analysis.summary}
        </p>
      </div>

      {/* Missing Keywords & Hard Skills Gap */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs">
        <div className="flex items-center justify-between gap-2 mb-3">
          <h4 className="text-xs font-bold text-slate-400 uppercase tracking-wider flex items-center gap-2">
            <AlertTriangle className="w-4 h-4 text-amber-500" />
            Critical Missing Keywords (Target Job Requirements)
          </h4>
          <span className="text-xs text-slate-400 font-medium">
            Click any tag to copy or rewrite
          </span>
        </div>
        <p className="text-xs text-slate-500 mb-4">
          Enterprise ATS screeners filter out resumes that lack these verbatim terms. Weave them into your past bullet points naturally.
        </p>

        <div className="flex flex-wrap gap-2">
          {(analysis.missing_keywords || []).map((keyword) => (
            <div
              key={keyword}
              className="group inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-semibold bg-amber-50 text-amber-900 border border-amber-200/80 hover:bg-amber-100 hover:border-amber-400 transition-all cursor-pointer"
              onClick={() => handleCopyKeyword(keyword)}
              title="Click to copy keyword"
            >
              <span>{keyword}</span>
              {copiedKeyword === keyword ? (
                <Check className="w-3.5 h-3.5 text-emerald-600" />
              ) : (
                <Copy className="w-3 h-3 text-amber-500 opacity-60 group-hover:opacity-100" />
              )}
              {onSendToRewriter && (
                <button
                  type="button"
                  onClick={(e) => {
                    e.stopPropagation();
                    onSendToRewriter(keyword);
                  }}
                  className="ml-1 pl-1 border-l border-amber-300 text-[10px] text-orange-600 hover:underline"
                  title="Rewrite bullet using this keyword"
                >
                  Rewrite ✍️
                </button>
              )}
            </div>
          ))}
        </div>
      </div>

      {/* Strengths & Actionable Improvements Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {/* Strengths */}
        <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs flex flex-col justify-between">
          <div>
            <h4 className="text-xs font-bold text-slate-400 uppercase tracking-wider mb-4 flex items-center gap-2">
              <CheckCircle2 className="w-4 h-4 text-emerald-500" />
              What Your Resume Does Well
            </h4>
            <ul className="space-y-3">
              {(analysis.strengths || []).map((strength, idx) => (
                <li key={idx} className="flex items-start gap-2.5 text-xs text-slate-700 leading-relaxed">
                  <span className="shrink-0 w-4 h-4 rounded-full bg-emerald-100 text-emerald-700 flex items-center justify-center font-bold text-[10px] mt-0.5">
                    ✓
                  </span>
                  <span>{strength}</span>
                </li>
              ))}
            </ul>
          </div>
        </div>

        {/* Improvements */}
        <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs flex flex-col justify-between">
          <div>
            <h4 className="text-xs font-bold text-slate-400 uppercase tracking-wider mb-4 flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-orange-500" />
              Actionable Bullet Improvements
            </h4>
            <ul className="space-y-3">
              {(analysis.improvements || []).map((imp, idx) => (
                <li key={idx} className="flex items-start gap-2.5 text-xs text-slate-700 leading-relaxed">
                  <span className="shrink-0 w-4 h-4 rounded-full bg-orange-100 text-orange-700 flex items-center justify-center font-bold text-[10px] mt-0.5">
                    {idx + 1}
                  </span>
                  <span>{imp}</span>
                </li>
              ))}
            </ul>
          </div>
        </div>
      </div>

      {/* Anticipated Interview Questions */}
      {analysis.interview_prep_questions && analysis.interview_prep_questions.length > 0 && (
        <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs">
          <h4 className="text-xs font-bold text-slate-400 uppercase tracking-wider mb-3 flex items-center gap-2">
            <HelpCircle className="w-4 h-4 text-indigo-500" />
            Top Interview Questions You Will Be Asked (Based on Gaps)
          </h4>
          <p className="text-xs text-slate-500 mb-4">
            Interviewers will probe these exact areas where your resume shows discrepancies with the job description.
          </p>

          <div className="space-y-2.5">
            {analysis.interview_prep_questions.map((question, idx) => (
              <div
                key={idx}
                className="p-3.5 rounded-xl bg-slate-50 border border-slate-200/80 flex items-start justify-between gap-3 text-xs"
              >
                <div className="flex items-start gap-2.5">
                  <span className="font-bold text-slate-400 shrink-0">Q{idx + 1}.</span>
                  <span className="font-medium text-slate-800">{question}</span>
                </div>
                {onAskCopilot && (
                  <button
                    onClick={() => onAskCopilot(`How should I prepare and answer this interview question: "${question}"?`)}
                    className="shrink-0 inline-flex items-center gap-1 text-[11px] font-semibold text-orange-600 hover:text-orange-700 bg-orange-50 hover:bg-orange-100 px-2 py-1 rounded-md transition-colors"
                  >
                    <span>Practice with Copilot</span>
                    <ChevronRight className="w-3 h-3" />
                  </button>
                )}
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Cover Letter Opening Hook */}
      {analysis.cover_letter_hook && (
        <div className="bg-gradient-to-r from-orange-50/70 via-amber-50/40 to-white p-6 rounded-2xl border border-orange-200/80 shadow-xs">
          <div className="flex items-center justify-between gap-2 mb-2">
            <h4 className="text-xs font-bold text-orange-800 uppercase tracking-wider flex items-center gap-2">
              <FileText className="w-4 h-4 text-orange-600" />
              Tailored Cover Letter Opening Hook
            </h4>
            <button
              onClick={handleCopyHook}
              className="inline-flex items-center gap-1.5 text-xs font-semibold px-2.5 py-1 rounded-lg bg-white border border-orange-200 text-orange-700 hover:bg-orange-50 shadow-xs transition-all"
            >
              {copiedHook ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copiedHook ? 'Copied to Clipboard!' : 'Copy Hook'}</span>
            </button>
          </div>
          <blockquote className="text-xs md:text-sm text-slate-800 italic pl-3 border-l-2 border-orange-400 my-2">
            "{analysis.cover_letter_hook}"
          </blockquote>
          <p className="text-[11px] text-slate-500 mt-2">
            Paste this directly into the first paragraph of your application note or LinkedIn outreach to the hiring manager.
          </p>
        </div>
      )}
    </div>
  );
};
